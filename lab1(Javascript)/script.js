// **var**
var nome = "João";
console.log(nome); // Output: João

nome = "Maria";
console.log(nome); // Output: Maria

// **let**
let curso = "info Web";
console.log(curso); // Output: info Web

let idade = 20;
console.log(idade); // Output: 20

idade = 21;
console.log(idade); // Output: 21

// **const**
const PI = 3.14;
console.log(PI); // Output: 3.14

//const NOTA = 10;
//NOTA = 9; // Isso causará um erro, pois não é possível reatribuir um valor a uma constante

// **Tipos de Dados**

// String
let frase = "Olá, mundo!";
console.log(typeof frase); // Output: string

// Number
let numero = 10;
console.log(typeof numero); // Output: number

// Boolean
let verdadeiro = true;
console.log(typeof verdadeiro); // Output: boolean

// Array
let lista = ["banana", "maçã", "laranja"];
console.log(typeof lista); // Output: object

 // nova array
let preços = [
    1.99, 
    "JOIA",
    3.99,
    "PRATA",
    5.99,
    "OURO"
];
console.log(typeof preços); // Output: object


// Object
let pessoa = { nome: "João", idade: 20 };
console.log(typeof pessoa); // Output: object



// null
let nulo = null;
console.log(typeof nulo); // Output: object

// undefined
let indefinido;
console.log(typeof indefinido); // Output: undefined